/**
 * Resolves a path using some fuzzy logic.
 *
 * Warning: If you use this function, try to pass a 'good' path. This function
 *          doesn't guarantee that the matches are logically best-matches.
 *
 * This function operates on the category aliases. It compares the given path with the
 * urlpaths generated by function prCreateURLNameLocationString() based on category aliases.
 *
 * @param string $path Path to resolve
 * @return int Closest matching category ID (idcat)
 * @throws cDbException|cException|cInvalidArgumentException
 */
function prResolvePathViaURLNames(string $path): int
{
    global $cfg, $lang, $client;

    if (empty($path)) {
        return 0;
    }

    $handle = startTiming('prResolvePathViaURLNames', [$path]);

    // Initialize variables
    $db = cRegistry::getDb();
    $categories = [];
    $results = [];

    // Pre-process path
    $path = cString::toLowerCase(str_replace(' ', '', $path));
    $pathresolveHeapcacheEnabled = cRegistry::getConfigValue('pathresolve_heapcache');

    // Delete outdated entry in heapcache table, if enabled.
    if ($pathresolveHeapcacheEnabled === true) {
        $oPathresolveCacheColl = new cApiPathresolveCacheCollection();
        $oPathresolveCache = $oPathresolveCacheColl->fetchLatestByPathAndLanguage($path, $lang);
        if (is_object($oPathresolveCache)) {
            if ($oPathresolveCache->isCacheTimeExpired()) {
                $cacheIdcat = $oPathresolveCache->get('idcat');
                $oPathresolveCacheColl->delete($oPathresolveCache->get('idpathresolvecache'));
                return $cacheIdcat;
            }
        }
    }

    // Fetch all category names, build path strings
    // @todo change the where statement for get all languages
    $sql = sprintf(
        "SELECT * FROM `%s` AS A, `%s` AS B, `%s` AS C 
             WHERE A.idcat = B.idcat AND B.idcat = C.idcat AND C.idlang = %d
             AND C.visible = 1 AND B.idclient=%d ORDER BY A.idtree",
        $cfg['tab']['cat_tree'],
        $cfg['tab']['cat'],
        $cfg['tab']['cat_lang'],
        $lang,
        $client
    );
    $db->query($sql);

    $catpath = [];
    while ($db->nextRecord()) {
        $categoryString = '';
        prCreateURLNameLocationString(
            (int) $db->f('idcat'),
            '/',
            $categoryString,
            false,
            '',
            0,
            0,
            true,
            true
        );

        // Store path
        $catpath[$db->f('idcat')] = $categoryString;
        $catnames[$db->f('idcat')] = $db->f('name');
        $catlevels[$db->f('idcat')] = $db->f('level');
    }

    // Compare strings using the similar_text algorithm
    $percent = 0;
    foreach ($catpath as $key => $value) {
        $value = cString::toLowerCase(str_replace(' ', '', $value));

        similar_text($value, $path, $percent);

        $firstpath = cString::findFirstPos($value, '/');

        if ($firstpath !== 0) {
            $xpath = cString::getPartOfString($value, $firstpath);
            $ypath = cString::getPartOfString($path, 0, cString::getStringLength($path) - 1);
            if ($xpath == $ypath) {
                $results[$key] = 100;
            } else {
                $results[$key] = $percent;
            }
        } else {
            $results[$key] = $percent;
        }
    }

    arsort($results, SORT_NUMERIC);

    endAndLogTiming($handle);

    if ($pathresolveHeapcacheEnabled === true) {
        $oPathresolveCacheColl = new cApiPathresolveCacheCollection();
        $oPathresolveCache = $oPathresolveCacheColl->create($path, key($results), $lang, time());
    }

    return (int)key($results);
}

/**
 * Resolves a path using some fuzzy logic.
 *
 * Warning: If you use this function, try to pass a 'good' path. This function
 *          doesn't guarantee that the matches are logically best-matches.
 *
 * This function operates on the actual category names.
 *
 * @param string $path Path to resolve
 * @param string $iLangCheck
 * @return int Closest matching category ID (idcat)
 * @throws cDbException|cException|cInvalidArgumentException
 */
function prResolvePathViaCategoryNames($path, &$iLangCheck): int
{
    global $cfg, $lang, $client;

    if (empty($path)) {
        return 0;
    }

    $handle = startTiming('prResolvePathViaCategoryNames', [$path]);

    // Initialize variables
    $db = cRegistry::getDb();
    $categories = [];
    $results = [];
    $iLangCheckOrg = $iLangCheck;

    // To take only path body
    if (preg_match('/^\/(.*)\/$/', $path, $aResults)) {
        $aResult = explode('/', $aResults[1]);
    } elseif (preg_match('/^\/(.*)$/', $path, $aResults)) {
        $aResult = explode('/', $aResults[1]);
    } else {
        $aResults[1] = $path;
    }

    $aResults[1] = cString::toLowerCase(preg_replace('/-/', ' ', $aResults[1]));

    // Init to Compare, save path in array
    $aPathsToCompare = explode('/', $aResults[1]);
    $iCountPath = count($aPathsToCompare);

    // init lang id
    $iLangCheck = 0;

    // Pre-process path
    $path = cString::toLowerCase(str_replace(' ', '', $path));

    // Fetch all category names, build path strings
    // @todo change the where statement for get all languages
    $sql = sprintf(
        "SELECT * FROM `%s` AS A, `%s` AS B, `%s` AS C WHERE A.idcat = B.idcat AND B.idcat = C.idcat
            AND C.visible = 1 AND B.idclient = %d ORDER BY A.idtree",
        $cfg['tab']['cat_tree'],
        $cfg['tab']['cat'],
        $cfg['tab']['cat_lang'],
        $client
    );
    $db->query($sql);

    $catpath = [];
    $arrLangMatches = [];

    while ($db->nextRecord()) {
        $categoryString = '';
        $aTemp = '';
        $iFor = 0;
        $bLang = false;

        // $level is changeless 0!!!
        conCreateLocationString(
            (int) $db->f('idcat'),
            '/',
            $categoryString,
            false,
            '',
            0,
            (int) $db->f('idlang')
        );
        // Store path
        $catpath[$db->f('idcat')] = $categoryString;
        $catnames[$db->f('idcat')] = $db->f('name');
        $catlevels[$db->f('idcat')] = $db->f('level');

        // Init variables for take a language id
        $aTemp = cString::toLowerCase($categoryString);
        $aDBToCompare = explode('/', $aTemp);
        $iCountDB = count($aDBToCompare);
        $iCountDBFor = $iCountDB - 1;
        // take min. count of two arrays
        ($iCountDB > $iCountPath) ? $iFor = $iCountPath : $iFor = $iCountDB;
        $iCountM = $iFor - 1;

        for ($i = 0; $i < $iFor; $i++) {
            if ($aPathsToCompare[$iCountM] == $aDBToCompare[$iCountDBFor]) {
                $bLang = true;
            } else {
                $bLang = false;
            }
            $iCountM--;
            $iCountDBFor--;
            // compare, only if current element is lastone and we are in true path
            if ($i == $iFor - 1 && $bLang) {
                $iLangCheck = $db->f('idlang');
                $arrLangMatches[] = $iLangCheck;
            }
        }
    }

    // Suppress wrongly language change if url name can be found in current language
    if ($iLangCheckOrg == 0) {
        if (in_array($lang, $arrLangMatches)) {
            $iLangCheck = $lang;
        }
    }

    // Compare strings using the similar_text algorithm
    $percent = 0;
    foreach ($catpath as $key => $value) {
        $value = cString::toLowerCase(str_replace(' ', '', $value));
        similar_text($value, $path, $percent);
        $results[$key] = $percent;
    }

    foreach ($catnames as $key => $value) {
        $value = cString::toLowerCase(str_replace(' ', '', $value));
        similar_text($value, $path, $percent);

        // Apply weight
        $percent = $percent * $catlevels[$key];

        if ($results[$key] > $percent) {
            $results[$key] = $percent;
        }
    }

    arsort($results, SORT_NUMERIC);

    endAndLogTiming($handle);
    return (int)key($results);
}

/**
 * Recursive function to create an URL name location string.
 *
 * @param int $idcat ID of the starting category
 * @param string $seperator Separation string
 * @param string $categoryString Category location string (by reference)
 * @param bool $makeLink create location string with links
 * @param string $linkClass stylesheet class for the links
 * @param int $firstTreeElementToUse first navigation level location string should be printed out (first level = 0!!)
 * @param int $uselang
 * @param bool $final
 * @param bool $usecache
 * @return void
 * @throws cDbException|cException
 */
function prCreateURLNameLocationString(
    $idcat,
    $seperator,
    &$categoryString,
    $makeLink = false,
    $linkClass = '',
    $firstTreeElementToUse = 0,
    $uselang = 0,
    $final = true,
    $usecache = false
)
{
    global $_URLlocationStringCache;

    $client = cRegistry::getClientId();
    $lang = cRegistry::getLanguageId();
    $cfg = cRegistry::getConfig();
    $sess = cRegistry::getSession();
    $uselang = cSecurity::toInteger($uselang);

    if ($final == true) {
        $categoryString = '';
    }

    if ($idcat == 0) {
        $categoryString = i18n("Lost and found");
        return;
    }

    if ($uselang == 0) {
        $uselang = $lang;
    }

    if ($final == true && $usecache == true) {
        if (!is_array($_URLlocationStringCache)) {
            $_URLlocationStringCache = prGetCacheFileContent($client, $uselang);
        }

        if (array_key_exists($idcat, $_URLlocationStringCache)) {
            if ($_URLlocationStringCache[$idcat]['expires'] > time()) {
                $categoryString = $_URLlocationStringCache[$idcat]['name'];
                return;
            }
        }
    }

    $db = cRegistry::getDb();

    $sql = "SELECT
                a.urlname AS urlname,
                a.name    AS name,
                a.idcat AS idcat,
                b.parentid AS parentid,
                c.level as level,
                d.idtpl as idtpl
            FROM
                " . $cfg['tab']['cat_lang'] . " AS a
                LEFT JOIN " . $cfg['tab']['tpl_conf'] . " AS d on a.idtplcfg  = d.idtplcfg,
                " . $cfg['tab']['cat'] . " AS b,
                " . $cfg['tab']['cat_tree'] . " AS c
            WHERE
                a.idlang    = " . (int)$uselang . " AND
                b.idclient  = " . (int)$client . " AND
                b.idcat     = " . (int)$idcat . " AND
                a.idcat     = b.idcat AND
                c.idcat     = b.idcat";

    $db->query($sql);
    $db->nextRecord();

    if ($db->f('level') >= $firstTreeElementToUse) {
        $name = $db->f('urlname');

        if (trim($name) == '') {
            $name = $db->f('name');
        }

        $parentid = $db->f('parentid');
        $idtpl = (int)$db->f('idtpl');

        //create link

        if ($makeLink == true) {
            $linkUrl = $sess->url("front_content.php?idcat=$idcat&idtpl=$idtpl");
            $name = '<a href="' . $linkUrl . '" class="' . $linkClass . '">' . $name . '</a>';
        }

        $tmp_cat_str = $name . $seperator . $categoryString;
        $categoryString = $tmp_cat_str;
    }

    if ($parentid != 0) {
        prCreateURLNameLocationString(
            $parentid,
            $seperator,
            $categoryString,
            $makeLink,
            $linkClass,
            $firstTreeElementToUse,
            $uselang,
            false,
            $usecache
        );
    } else {
        $sep_length = cString::getStringLength($seperator);
        $str_length = cString::getStringLength($categoryString);
        $tmp_length = $str_length - $sep_length;
        $categoryString = cString::getPartOfString($categoryString, 0, $tmp_length);
    }

    if ($final == true && $usecache == true) {
        $_URLlocationStringCache[$idcat]['name'] = $categoryString;
        $_URLlocationStringCache[$idcat]['expires'] = time() + 3600;

        prWriteCacheFileContent($_URLlocationStringCache, $client, $uselang);
    }
}

/**
 * Writes path location string cache data file.
 *
 * @throws cInvalidArgumentException
 */
function prWriteCacheFileContent(array $data, int $client, int $lang): bool
{
    $cfgClient = cRegistry::getClientConfig();
    $path = $cfgClient[$client]['cache']['path'];
    $filename = "locationstring-url-cache-$lang.txt";

    $res = false;
    if (is_writable($path)) {
        $res = cFileHandler::write($path . $filename, serialize($data));
    }

    return $res;
}

/**
 * Get path location string cache data file content.
 *
 * @throws cInvalidArgumentException
 */
function prGetCacheFileContent(int $client, int $lang): array
{
    $cfgClient = cRegistry::getClientConfig();
    $path = $cfgClient[$client]['cache']['path'];
    $filename = "locationstring-url-cache-$lang.txt";

    if (cFileHandler::exists($path . $filename)) {
        $data = unserialize(cFileHandler::read($path . $filename));
    } else {
        $data = [];
    }

    return is_array($data) ? $data : [];
}

/**
 * Deletes path location string cache data file.
 */
function prDeleteCacheFileContent(int $client, int $lang): bool
{
    $cfgClient = cRegistry::getClientConfig();
    $path = $cfgClient[$client]['cache']['path'];
    $filename = "locationstring-url-cache-$lang.txt";

    $res = false;
    if (is_writable($path . $filename)) {
        $res = @unlink($path . $filename);
    }

    return ($res) ? true : false;
}
